"""
Paradigms in the slf format of MorphWizard (aot.ru): a paradigm is a list of lines `form POS grammems`,
the first line is the lemma, paradigms are separated by `=====`, the grammems common to all forms
(animacy of nouns, aspect and transitivity of verbs) are given in the field `$type_grm`.
The POS and grammems are the Latin names of the Russian gramtab (morph_dict/data/Russian/gramtab.json),
a line must match a line of the gramtab exactly, e.g. `N mas,sg,nom`, `A mas,sg,acc,anim`.
"""
import re
from typing import Dict, List, Optional, Tuple
from unicodedata import normalize

GENDERS: Dict[str, str] = {"m": "mas", "n": "neu", "f": "fem"}
ANIMACY: Dict[str, str] = {"a": "anim", "n": "inanim"}
BOTH_ANIMACY = "anim,inanim"
TENSES: Dict[str, str] = {"prs": "pres", "pst": "past"}
VOICES: Dict[str, str] = {"act": "act", "pass": "pass"}

# the parts of speech of `generated_forms["inv"]`, see INVARIABLE_TEMPLATES
INVARIABLE_POS: Dict[str, str] = {
    "adv": "ADV",
    # aot gives the present to predicatives: `можно PRED pres`
    "pred": "PRED pres",
    "particle": "PARTICLE",
    "prep": "PREP",
    "conj": "CONJ",
    "intrj": "INT",
    "ono": "INT",
    "par": "INP",
    # `его`, `её`, `их`
    "pron": "PA 0,anim,inanim",
    "num": "NUM nom",
}

# the other parts of speech of a word (the field `also`): `быстро` is also a predicative
ALSO_POS: List[Tuple[str, str]] = [
    ("предикатив", "PRED pres"),
    ("предиктив", "PRED pres"),
    ("вводн", "INP"),
    ("частица", "PARTICLE"),
    ("союз", "CONJ"),
    ("междометие", "INT"),
    ("предлог", "PREP"),
    ("послелог", "POSL"),
    ("наречие", "ADV"),
]

ABBREVIATION_POS: Dict[str, str] = {
    "adj": "A 0,anim,inanim",
    "adv": "ADV",
    "intrj": "INT",
    "par": "INP",
    "prep": "PREP",
}

# personal pronouns: person and number, the other pronouns with a table of cases are `кто` or `что`
PERSONAL_PRONOUNS: Dict[str, str] = {
    "я": "1p,sg", "ты": "2p,sg", "мы": "1p,pl", "вы": "2p,pl",
    "он": "3p,mas,sg", "она": "3p,fem,sg", "оно": "3p,neu,sg", "они": "3p,pl",
}

FORM_PATTERN = re.compile(r"^[а-яё]+(-[а-яё]+)*$")


def clean_form(form: str) -> Optional[str]:
    """
    A form without segment separators and stress marks in lower case, None if it is not a Russian word
    (an analytic form `ни о ком`, a form with digits or Latin letters).
    """
    form = normalize("NFD", form.replace("|", "").strip().lower())
    form = normalize("NFC", re.sub("[̀́]", "", form))
    return form if FORM_PATTERN.match(form) else None


def adjective_grammems(name: str) -> List[str]:
    """
    The grammems of a full adjective form: `nom-sg-m` -> `mas,sg,nom,anim,inanim`,
    `acc-sg-m-a` -> `mas,sg,acc,anim`, `acc-pl-n` -> `pl,acc,inanim`, `acc-sg-n` is the neuter.
    The masculine and plural accusative without animacy (`acc-sg-m` of `оне`) are both forms.
    :return: one line of grammems or two, empty if the name is unknown
    """
    parts = name.split("-")
    case, rest = parts[0], parts[1:]
    animacy = [BOTH_ANIMACY]
    if case == "acc" and len(rest) == (2 if rest[:1] == ["pl"] else 3) and rest[-1] in ANIMACY:
        animacy = [ANIMACY[rest.pop()]]
    elif case == "acc" and rest in (["pl"], ["sg", "m"]):
        animacy = list(ANIMACY.values())
    if rest == ["pl"]:
        return [f"pl,{case},{a}" for a in animacy]
    if len(rest) == 2 and rest[0] == "sg" and rest[1] in GENDERS:
        return [f"{GENDERS[rest[1]]},sg,{case},{a}" for a in animacy]
    return []


def short_grammems(name: str) -> Optional[str]:
    """
    `srt-sg-m` -> `mas,sg`, `srt-pl` -> `pl`
    """
    rest = name.split("-")[1:]
    if rest == ["pl"]:
        return "pl"
    if len(rest) == 2 and rest[0] == "sg" and rest[1] in GENDERS:
        return f"{GENDERS[rest[1]]},sg"
    return None


def case_table_grammems(name: str, with_genders: bool) -> Optional[Tuple[str, str]]:
    """
    The names of the case tables of pronouns and numerals: `nom`, `acc-a`, `nom-m`, `acc-m-n`, `nom-pl`.
    :param with_genders: the table has gender columns, so `acc-n` is the neuter, not the inanimate form
    :return: the case and the gender or `pl` (or "")
    """
    parts = name.split("-")
    case, rest = parts[0], parts[1:]
    if case == "acc" and rest and rest[-1] in ANIMACY and (len(rest) == 2 or not with_genders):
        rest.pop()
    if not rest:
        return case, ""
    if len(rest) == 1 and rest[0] in GENDERS:
        return case, GENDERS[rest[0]]
    if rest == ["pl"]:
        return case, "pl"
    if len(rest) == 2 and rest[0] == "sg" and rest[1] in GENDERS:
        return case, GENDERS[rest[1]]
    return None


def form_values(value) -> List[str]:
    # nouns are generated by the original parser with one form per name
    return [value] if isinstance(value, str) else value


class TParadigm:
    """
    The lines of one slf paradigm, the lemma is the first one.
    """
    def __init__(self, type_grammems: str = ""):
        self.lines: List[Tuple[str, str]] = []
        self.type_grammems = type_grammems
        self.skipped: List[str] = []

    def add(self, forms, annotation, first: bool = False):
        """
        :param annotation: a line of POS and grammems or a list of them
        """
        if isinstance(annotation, list):
            for one in annotation:
                self.add(forms, one, first)
                first = False
            return
        for form in form_values(forms):
            cleaned = clean_form(form)
            if cleaned is None:
                self.skipped.append(form)
                continue
            line = (cleaned, annotation)
            if line in self.lines:
                continue
            if first:
                self.lines.insert(0, line)
                first = False
            else:
                self.lines.append(line)

    def to_slf(self, comment: str) -> str:
        result = ["=====", f"// {comment}"]
        if self.type_grammems:
            result.append(f"$type_grm = {self.type_grammems}")
        result.extend(f"{form} {annotation}" for form, annotation in self.lines)
        return "\n".join(result) + "\n"


def add_lemma_first(paradigm: TParadigm, forms: Dict[str, List[str]], names: List[str], annotate) -> None:
    """
    Adds the forms of the first present name of `names` as the lemma, then all the others.
    """
    lemma_name = next((name for name in names if forms.get(name)), None)
    if lemma_name:
        paradigm.add(form_values(forms[lemma_name])[:1], annotate(lemma_name), first=True)
    for name, values in forms.items():
        annotation = annotate(name)
        if annotation:
            paradigm.add(values, annotation)


def all_forms_equal(forms: Dict[str, List[str]]) -> bool:
    return len({clean_form(f) for values in forms.values() for f in form_values(values)}) == 1


def noun_paradigm(article: dict) -> Tuple[Optional[TParadigm], str]:
    """
    Nouns of the template `сущ ru m a 1a`: gender, animacy, `pt` for plurale tantum, the index `0` for
    indeclinable nouns. Variants `gen-sg2` are other forms with the same grammems.
    """
    words = article["morpho"]["template"].split()[2:]
    gender = next((GENDERS[w] for w in words if w in GENDERS), None)
    plural_only = "pt" in words
    animacy = "anim" if "a" in words else "inanim" if "ina" in words else ""
    if plural_only:
        gender = "pl"
    elif article["morpho"]["info"].get("род", "").strip() == "общ":
        # the common gender: `бедняга`, `верзила`
        gender = "mas,fem"
    if gender is None:
        return None, "род не указан в шаблоне"
    paradigm = TParadigm(animacy)
    forms = article["generated_forms"]
    if any(w.startswith("0") for w in words) and all_forms_equal(forms):
        paradigm.add(form_values(next(iter(forms.values())))[:1], f"N {gender},0")
        return paradigm, ""

    def annotate(name: str) -> Optional[str]:
        case, number = name.split("-")
        number = number.rstrip("2")
        if plural_only:
            return f"N pl,{case}"
        return f"N {gender},{number},{case}"
    add_lemma_first(paradigm, forms, ["nom-sg", "nom-pl"], annotate)
    return paradigm, ""


def adjective_paradigm(article: dict, pos: str = "A", type_grammems: str = "") -> TParadigm:
    paradigm = TParadigm(type_grammems)
    forms = article["generated_forms"]
    if pos == "A" and len(forms) > 1 and all_forms_equal(forms):
        # indeclinable adjectives: `беж`, `бордо`
        paradigm.add(form_values(next(iter(forms.values())))[:1], "A 0,anim,inanim")
        return paradigm

    def annotate(name: str) -> Optional[str]:
        if name == "comp":
            return "A compar,anim,inanim" if pos == "A" else None
        if name.startswith("srt-"):
            grammems = short_grammems(name)
            if not grammems:
                return None
            # short forms of pronouns: `каков`, `таков`
            return f"ADJ_SHORT {grammems},anim,inanim" if pos == "A" else \
                f"{pos} {grammems},nom,anim,inanim"
        return [f"{pos} {grammems}" for grammems in adjective_grammems(name)] or None
    add_lemma_first(paradigm, forms, ["nom-sg-m", "nom-pl"], annotate)
    return paradigm


VERB_FORMS: Dict[str, str] = {
    "inf": "INFINITIVE act",
    "pst-sg-m": "V act,past,mas,sg",
    "pst-sg-f": "V act,past,fem,sg",
    "pst-sg-n": "V act,past,neu,sg",
    "pst-pl": "V act,past,pl",
    "imp-sg-2": "V act,imp,2p,sg",
    "imp-pl-2": "V act,imp,2p,pl",
    "imp-pl-1": "V act,imp,1p,pl",
    "ger-prs": "ADV_PARTICIPLE act,pres",
    "ger-pst": "ADV_PARTICIPLE act,past",
}
VERB_ASPECTS: Dict[str, Tuple[List[str], str]] = {
    "impf": (["pres"], "imperf"),
    "pf": (["fut"], "perf"),
    "both": (["pres", "fut"], "perf,imperf"),
}


def verb_paradigm(article: dict) -> Tuple[Optional[TParadigm], str]:
    """
    A verb with participles and gerunds is one paradigm, as in aot. The non-past forms are the present
    for imperfective verbs, the future for perfective ones and both for biaspectual ones.
    """
    if article.get("aspect") not in VERB_ASPECTS:
        return None, "вид не указан"
    tenses, aspect = VERB_ASPECTS[article["aspect"]]
    transitivity = "trans" if article.get("transitive") else "intrans"
    paradigm = TParadigm(f"{aspect},{transitivity}")
    forms = article["generated_forms"]
    paradigm.add(forms.get("inf", [])[:1], VERB_FORMS["inf"], first=True)
    for name, values in forms.items():
        if name in VERB_FORMS:
            paradigm.add(values, VERB_FORMS[name])
        elif name.startswith("npst-"):
            _, number, person = name.split("-")
            for tense in tenses:
                paradigm.add(values, f"V act,{tense},{person}p,{number}")
        elif name.startswith("ptcp-"):
            _, tense, voice, adjective_name = name.split("-", 3)
            tense, voice = TENSES[tense], VOICES[voice]
            if adjective_name.startswith("srt-"):
                grammems = short_grammems(adjective_name)
                paradigm.add(values, f"PARTICIPLE_SHORT anim,inanim,{tense},{voice},{grammems}")
            else:
                paradigm.add(values, [f"PARTICIPLE {tense},{voice},{grammems}"
                                      for grammems in adjective_grammems(adjective_name)])
    return paradigm, ""


def surname_paradigm(article: dict) -> TParadigm:
    """
    The masculine and the feminine surname are one paradigm, the plural is common: `N mas,fem,pl,nom`.
    """
    paradigm = TParadigm("anim,surname")
    forms = article["generated_forms"]
    if all_forms_equal(forms):
        paradigm.add(forms["nom-sg-m"][:1], "N mas,fem,0")
        return paradigm

    # an indeclinable feminine surname is one form, as in aot: `Хворост N fem,0`
    feminine = {name: values for name, values in forms.items() if name.endswith("-f")}
    feminine_indeclinable = len(feminine) == 6 and all_forms_equal(feminine)

    def annotate(name: str) -> Optional[str]:
        parts = name.split("-")
        if parts[1:] == ["pl"]:
            return f"N mas,fem,pl,{parts[0]}"
        if parts[2] == "f" and feminine_indeclinable:
            return "N fem,0" if parts[0] == "nom" else None
        return f"N {GENDERS[parts[2]]},sg,{parts[0]}"
    add_lemma_first(paradigm, forms, ["nom-sg-m"], annotate)
    return paradigm


def pronoun_case_paradigm(article: dict, pos: str) -> TParadigm:
    """
    Pronouns and numerals with a table of cases: `кто`, `я`, `пять`, `два` (genders), `пятеро`.
    """
    forms = article["generated_forms"]
    with_genders = any(re.match(r"^[a-z]+-(sg-)?[mf]\b", name) for name in forms)
    title = article["title"]
    paradigm = TParadigm()
    if pos == "PRON":
        if title in PERSONAL_PRONOUNS:
            base = PERSONAL_PRONOUNS[title]
        elif "nom" not in forms and title.startswith("не"):
            # `некого`, `нечего`
            pos, base = "P_PRED", "sg"
        else:
            base = "neu,sg" if re.search("что|чё|сё", title) else "mas,sg"

    def annotate(name: str) -> Optional[str]:
        parsed = case_table_grammems(name, with_genders)
        if not parsed:
            return None
        case, gender = parsed
        if pos == "NUM":
            return f"NUM {gender},{case}" if gender in GENDERS.values() else f"NUM {case}"
        if gender == "pl":
            return f"PRON pl,{case}"
        if gender:
            return f"PRON {gender},sg,{case}"
        return f"{pos} {base},{case}"
    add_lemma_first(paradigm, forms, ["nom", "nom-m", "nom-sg-m", "nom-pl"], annotate)
    return paradigm


def also_pos(value: str) -> Optional[str]:
    value = re.sub(r"\[\[|\]\]", "", value).strip()
    for prefix, pos in ALSO_POS:
        if value.startswith(prefix):
            return pos
    return None


def other_paradigms(article: dict) -> Tuple[List[TParadigm], str]:
    """
    Invariable words, pronouns, numerals, possessive adjectives and abbreviations from other.jsonl.
    An adverb has the comparative of its adjective, e.g. `быстрее`, in aot it is a form of the adjective,
    so it is not exported.
    """
    pos = article["pos"]
    forms = article["generated_forms"]
    if pos == "padj":
        return [adjective_paradigm(article, "A", "poss")], ""
    if pos in ("pron", "num") and "nom-sg-m" in forms:
        is_ordinal = pos == "num"
        return [adjective_paradigm(article, "ORD_NUM" if is_ordinal else "PA")], ""
    if pos in ("pron", "num") and "inv" not in forms:
        return [pronoun_case_paradigm(article, "PRON" if pos == "pron" else "NUM")], ""
    if pos == "abbr":
        abbr_pos = article.get("abbr_pos", "noun")
        if abbr_pos == "noun":
            gender = GENDERS.get(article.get("gender"), "mas")
            if article.get("number") == "pl":
                annotation = "N pl,abbr,0"
            elif article.get("number") == "sg" and gender != "fem":
                # the gramtab has no line `N fem,sg,abbr,0`
                annotation = f"N {gender},sg,abbr,0"
            else:
                annotation = f"N {gender},abbr,0"
        elif abbr_pos in ABBREVIATION_POS:
            annotation = ABBREVIATION_POS[abbr_pos]
        else:
            return [], f"неизвестная часть речи сокращения {abbr_pos}"
    elif pos in INVARIABLE_POS:
        annotation = INVARIABLE_POS[pos]
    else:
        return [], f"неизвестная часть речи {pos}"
    if "inv" not in forms:
        return [], "нет формы inv"
    annotations = [annotation]
    for value in article.get("also", []):
        for part in value.split(","):
            other = also_pos(part)
            if other and other not in annotations:
                annotations.append(other)
    paradigms = []
    for annotation in annotations:
        paradigm = TParadigm()
        paradigm.add(forms["inv"], annotation)
        if annotation == "PRED pres" and forms.get("comp"):
            paradigm.add(forms["comp"], "PRED compar,pres")
        paradigms.append(paradigm)
    return paradigms, ""
